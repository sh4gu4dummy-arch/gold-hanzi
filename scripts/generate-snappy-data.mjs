#!/usr/bin/env node
/**
 * v0.029 snappy data:
 * - Split catalog → characters-classic.json + characters-v3-extra.json
 * - Batch stroke geometry into per-lesson JSON chunks (classic + v3)
 * - Emit charLessons.ts (glyph → lesson id) for the runtime loader
 *
 * Heavy strokeLessons/* are build artifacts (gitignored); catalogs + map are committed.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const dataDir = path.join(root, 'src/data')
const strokesDir = path.join(dataDir, 'strokes')
const lessonsDir = path.join(dataDir, 'strokeLessons')
const LESSON_SIZE = 12

const catalog = JSON.parse(
  fs.readFileSync(path.join(dataDir, 'characters.json'), 'utf8'),
)

const classic = catalog.filter((e) => e.hskClassic != null && e.hskClassic >= 1)
const v3Extra = catalog.filter(
  (e) => e.hskV3 != null && e.hskV3 >= 1 && (e.hskClassic == null || e.hskClassic < 1),
)

fs.writeFileSync(
  path.join(dataDir, 'characters-classic.json'),
  JSON.stringify(classic),
)
fs.writeFileSync(
  path.join(dataDir, 'characters-v3-extra.json'),
  JSON.stringify(v3Extra),
)

function bandsFor(entries, key) {
  const byLevel = new Map()
  for (const e of entries) {
    const level = e[key]
    if (level == null || level < 1) continue
    const list = byLevel.get(level) ?? []
    list.push(e)
    byLevel.set(level, list)
  }
  const bands = []
  for (const level of [...byLevel.keys()].sort((a, b) => a - b)) {
    const list = byLevel.get(level)
    const lessons = []
    for (let i = 0; i < list.length; i += LESSON_SIZE) {
      const slice = list.slice(i, i + LESSON_SIZE)
      const n = Math.floor(i / LESSON_SIZE) + 1
      lessons.push({
        id: `hsk${level}-l${n}`,
        entries: slice,
      })
    }
    bands.push({ level, lessons })
  }
  return bands
}

function readStroke(id) {
  const p = path.join(strokesDir, `${id}.json`)
  if (!fs.existsSync(p)) return null
  return JSON.parse(fs.readFileSync(p, 'utf8'))
}

function writeLessons(view, entries, key) {
  const outDir = path.join(lessonsDir, view)
  fs.mkdirSync(outDir, { recursive: true })
  // wipe old chunks for this view
  for (const f of fs.readdirSync(outDir)) {
    if (f.endsWith('.json')) fs.unlinkSync(path.join(outDir, f))
  }
  const charToLesson = {}
  let files = 0
  let missing = 0
  for (const band of bandsFor(entries, key)) {
    for (const lesson of band.lessons) {
      const payload = {}
      for (const e of lesson.entries) {
        const data = readStroke(e.id)
        if (!data) {
          missing += 1
          continue
        }
        payload[e.character] = data
        charToLesson[e.character] = lesson.id
      }
      fs.writeFileSync(
        path.join(outDir, `${lesson.id}.json`),
        JSON.stringify(payload),
      )
      files += 1
    }
  }
  return { charToLesson, files, missing }
}

// Classic lessons from classic list; v3 lessons from full catalog filtered by hskV3
const v3All = catalog.filter((e) => e.hskV3 != null && e.hskV3 >= 1)
const classicResult = writeLessons('classic', classic, 'hskClassic')
const v3Result = writeLessons('v3', v3All, 'hskV3')

const mapSrc = `/** Auto-generated by scripts/generate-snappy-data.mjs — do not edit. */
export const CHAR_CLASSIC_LESSON: Record<string, string> = ${JSON.stringify(classicResult.charToLesson)}

export const CHAR_V3_LESSON: Record<string, string> = ${JSON.stringify(v3Result.charToLesson)}
`

fs.writeFileSync(path.join(dataDir, 'charLessons.ts'), mapSrc)

const stats = {
  classicEntries: classic.length,
  v3ExtraEntries: v3Extra.length,
  classicLessonFiles: classicResult.files,
  v3LessonFiles: v3Result.files,
  classicMissingStrokes: classicResult.missing,
  v3MissingStrokes: v3Result.missing,
}
fs.mkdirSync(path.join(root, '_build'), { recursive: true })
fs.writeFileSync(
  path.join(root, '_build/v0029-snappy-stats.json'),
  JSON.stringify(stats, null, 2),
)
console.log('generate-snappy-data', stats)
